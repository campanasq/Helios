import { Ability } from './dnd';

export type CombatStyle = 'Melee' | 'Rango' | 'Híbrido';

export interface PixelRect {
  x: number;
  y: number;
  fill: string;
}

export interface DndClassInfo {
  name: string;
  combat: CombatStyle;
  spellcaster: boolean;
  spellcasterLabel: string;
  role: string;
  hitDice: string;
  savingThrows: Ability[];
  primaryAbilities: Ability[];
  spellAbility: Ability | '';
  tagline: string;
  description: string;
  accent: string;
  pixels: PixelRect[];
}

function buildPixels(grid: string[], palette: Record<string, string>): PixelRect[] {
  const rects: PixelRect[] = [];
  for (let y = 0; y < grid.length; y++) {
    const row = grid[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      const fill = palette[ch];
      if (fill) rects.push({ x, y, fill });
    }
  }
  return rects;
}

